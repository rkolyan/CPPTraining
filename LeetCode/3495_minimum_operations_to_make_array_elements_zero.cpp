class Solution2 {
public:
    long long minOperations(vector<vector<int>>& queries) {
        long long ans = 0;
        for (const auto& q : queries) {
            long long l = q[0], r = q[1];
            long long total_divs = 0;
            int k = 1;
            while (true) {
                long long low = (k == 1) ? 1 : (1LL << (2 * (k - 1)));
                long long high = (1LL << (2 * k)) - 1;
                if (low > r) break;
                long long L = max(l, low);
                long long R = min(r, high);
                if (L <= R) {
                    total_divs += (R - L + 1) * k;
                }
                ++k;
            }
            ans += (total_divs + 1) / 2;
        }
        return ans;
    }
};
