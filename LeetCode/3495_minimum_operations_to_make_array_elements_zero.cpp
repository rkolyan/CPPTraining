class Solution {
private:
    inline int g(int num) {
        int count = 0;
        while (num) {
            num /= 4;
            ++count;
        }
        return count;
    }
    inline long find_full_A_count(int n) {
        return 3 * (static_cast<long>(1) << (2*(n-1)));
    }
    long f(long count, int n) {
        if (count <= 0) {
            return 0;
        }
        return count * static_cast<long>(n/2) + ((count-1)/2 + 1)*(n & 1);
        /*
        1 1 1
        */
    }
    inline long f(int n) {
        return f(find_full_A_count(n), n);
    }
    inline long left_count(int left, int m) {
        return (static_cast<long>(1) << (2*m))-left;
    }
    inline long right_count(int right, int m) {
        return right - (static_cast<long>(1) << (2*(m-1))) + 1;
    }
public:
    long long minOperations(std::vector<std::vector<int>>& queries) {
        int m1, m2, k, l_count, r_count;
        constexpr int cache_size = sizeof(int)*4-1;
        long cache[cache_size+1][cache_size+1] = {0};
        for (int i = cache_size; i > 0; --i) {
            cache[i][i] = f(i);
            for (int j = i+1; j <= cache_size; ++j) {
                cache[i][j] = cache[i][j-1] + cache[j][j];
            }
        }
        int tmp_count = 0;
        long long operations_count = 0;
        for (const auto &query : queries) {
            m1 = g(query[0]);
            m2 = g(query[1]);
            k = m2 - m1;
            if (k > 1) {
                l_count = left_count(query[0], m1);
                r_count = right_count(query[1], m2);
                if (l_count % 2 == 0 || (l_count > 1 && m1 % 2 == 0)) {
                    //A_l 1 категория
                    if (r_count % 2 == 0) {
                        //A_r 1 категория
                        operations_count += f(l_count, m1) + f(r_count, m2) + cache[m1+1][m2-1];
                    } else {
                        //A_r 2 или 3 категория
                        tmp_count = find_full_A_count(m2-1);
                        operations_count += f(l_count, m1) + f(tmp_count+r_count, m2) - ((tmp_count-1)/2+1) + cache[m1+1][m2-2];
                    }
                } else {
                    if (r_count % 2 == 0 || (r_count > 1 && m2 % 2 == 0)) {
                        tmp_count = find_full_A_count(m1+1);
                        operations_count += (f(l_count+tmp_count, m1+1) - ((l_count-1)/2+1)) + cache[m1+2][m2-1] + f(r_count, m2);
                    } else {
                        operations_count += f(l_count-1, m1) + f(r_count-1,m2) + f(2, m1 + k/2) + (m1+m2)%2 + cache[m1+1][m2-1];
                    }
                }
            } else if (k == 1) {
                l_count = left_count(query[0], m1);
                r_count = right_count(query[1], m2);
                //возмножные случаи
                /*
                3 4 4 4 = f(4 4 4 4)
                2 3 3 3 = f(3 3 3 3)
                2 2 3 3 3 = f(5, 3) - 1
                3 3 4 4 4 = f(5, 4) - 1
                3 4 = f(2,4)
                2 3 = f(2,3)
                2 3 3 = f(3, 3)
                3 4 4 = f(4, 4,)
                2 2 2 3 3 3 3 = f(7, 3)-2
                */
                operations_count += f(l_count + r_count, m2) - ((l_count-1) / 2 + 1);
            } else {
                operations_count += f(query[1] - query[0] + 1, m1);                
            }
        }
        return operations_count;
    }
};

