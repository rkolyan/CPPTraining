std::vector<std::array<int, 3>> findSequence(int n) {
    std::vector<std::array<int, 3>> result;
    result.reserve(2 * n);
    for (int i = 1; i <= n; ++i) {
        if (i - 1) {
            result.push_back({i, 1, i});
        }
        if (n - (i + 1) > 0) {
            result.push_back({i, i + 1, n});
        }
    }
    return result;
}

int main(void) {
    int t = 0, n = 0;
    std::vector<std::array<int, 3>> result;
    std::cin >> t;
    while (t--) {
        std::cin >> n;
        result = findSequence(n);
        std::cout << result.size() << std::endl;
        for (const auto &subarray : result) {
            for (const auto &element : subarray) {
                std::cout << element << ' ';
            }
            std::cout << std::endl;
        }
    }
    return 0;
}